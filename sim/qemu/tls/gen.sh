#!/usr/bin/env bash
# Test-only TLS material for the https fake HA of `make qemu-contract` (#79). Not secret: the key below serves
# https://10.0.2.2 to a QEMU guest, and only x4qemu images trust the CA (firmware/src/hw/qemu_tls.cpp).
#   sim/qemu/tls/gen.sh   → ha.pem + ha.key (fake HA), firmware/src/hw/qemu_test_ca.h (CA cert). The CA key is thrown away.
set -euo pipefail
HERE="$(cd "$(dirname "$0")" && pwd)"
ROOT="$(cd "$HERE/../../.." && pwd)"
T="$(mktemp -d)"
trap 'rm -rf "$T"' EXIT
openssl ecparam -name prime256v1 -genkey -noout -out "$T/ca.key"
openssl req -x509 -new -key "$T/ca.key" -sha256 -days 7300 -subj "/CN=HA Paper QEMU test CA" \
  -addext "basicConstraints=critical,CA:TRUE" -addext "keyUsage=critical,keyCertSign" -out "$T/ca.pem"
openssl ecparam -name prime256v1 -genkey -noout -out "$HERE/ha.key"
openssl req -new -key "$HERE/ha.key" -subj "/CN=10.0.2.2" -out "$T/ha.csr"
printf 'basicConstraints=CA:FALSE\nkeyUsage=digitalSignature\nextendedKeyUsage=serverAuth\nsubjectAltName=DNS:10.0.2.2,IP:10.0.2.2,DNS:localhost,IP:127.0.0.1\n' >"$T/ext"
openssl x509 -req -in "$T/ha.csr" -CA "$T/ca.pem" -CAkey "$T/ca.key" -CAcreateserial -sha256 -days 7300 \
  -extfile "$T/ext" -out "$HERE/ha.pem"
{
  echo "// Generated by sim/qemu/tls/gen.sh: the test CA of the contract suite's https fake HA (x4qemu only, #79)."
  echo "#pragma once"
  echo "static const char kQemuTestCa[] ="
  sed 's/^/  "/; s/$/\\n"/' "$T/ca.pem"
  echo "  ;"
} >"$ROOT/firmware/src/hw/qemu_test_ca.h"
echo "wrote $HERE/ha.pem, $HERE/ha.key, firmware/src/hw/qemu_test_ca.h"
