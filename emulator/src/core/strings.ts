export type StrKey = keyof typeof STRINGS;

/** HA's `language` (get_config) or a browser language → 'nl' for any Dutch variant, 'en' for everything else. */
export function langOf(code: string | null | undefined): Lang {
  const base = String(code ?? '').trim().toLowerCase().split(/[-_]/)[0];
  return base === 'nl' ? 'nl' : 'en';
}

/** Console language (#98): HA's while linked and known, else the browser's (navigator.language). */
export function consoleLang(snap: { ha: { linked: boolean }; language: Lang | null } | null, browser: string): Lang {
  return snap?.ha.linked && snap.language ? langOf(snap.language) : langOf(browser);
}

/** The text for `key`, each "{}" replaced by the next arg (missing args leave "{}"). */
export function tr(lang: Lang, key: StrKey, ...args: (string | number)[]): string {
  const s: string = STRINGS[key][lang === 'nl' ? 1 : 0];
  let i = 0;
  return s.replace(/\{\}/g, (m) => (i < args.length ? String(args[i++]) : m));
}

/** Messages that arrive in English (device API errors, screen-editor checks): matched against these keys' English text. */
const MSG_KEYS: StrKey[] = ['pickNetwork', 'wifiPwShort', 'errPwMax', 'wrongPassword', 'errNetNotFound', 'errHaNoAnswer', 'noNetworkLater', 'errSignInFirst',
  'errAdmin', 'errWifiFirst', 'errEnterHa', 'errEnterHaDot', 'errHaRejected', 'errTooManyTokens', 'errUpToDate', 'errUnlinkFirst', 'errNotUrl',
  'errProbeBusy', 'errNotAddress', 'errNotHere', 'errScheme', 'errHttpOnly', 'errCantReach', 'errRedirects', 'errNotHa', 'noAnswer',
  'errCatName', 'errMaxCats', 'errMoveScreens', 'errKeepOneCat', 'errScreenFull', 'errNoRoomAt', 'errNoFreeSpot', 'errTileNoRoom', 'errNoRoomSize',
  'errScreenName', 'errPickEntity', 'errWrongDomain', 'errNotListed', 'errGaugeUnit'];
const esc = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
const MSG_RE: [RegExp, StrKey][] = MSG_KEYS.map((k) => [new RegExp('^' + STRINGS[k][0].split('{}').map(esc).join('(.+?)') + '$'), k]);

/** English text → key, for texts without a placeholder (first key wins; duplicates have the same Dutch). */
const EN_KEY = new Map<string, StrKey>();
for (const [k, [en]] of Object.entries(STRINGS)) if (!en.includes('{}') && !EN_KEY.has(en)) EN_KEY.set(en, k as StrKey);

/** A text the device, the screen editor or a shared table wrote in English (the wire stays English, #111), in `lang`:
 *  an exact match of a key's English, or a MSG_KEYS template. Unknown → as is. */
export function trMsg(lang: Lang, msg: string): string {
  if (lang === 'en' || !msg) return msg;
  const k = EN_KEY.get(msg); if (k) return tr(lang, k);
  for (const [re, key] of MSG_RE) { const m = re.exec(msg); if (m) return tr(lang, key, ...m.slice(1)); }
  return msg;
}

/** The text before and after the one {} of `key`, for a value set in bold between them. */
export function trParts(lang: Lang, key: StrKey): [string, string] {
  const s: string = STRINGS[key][lang === 'nl' ? 1 : 0];
  const i = s.indexOf('{}');
  return i < 0 ? [s, ''] : [s.slice(0, i), s.slice(i + 2)];
}

/** Clock date line, "Tuesday 13 October" / "Dinsdag 13 oktober". wday 0 = Sunday, month 0 = January (struct tm). */
export function dateLine(lang: Lang, wday: number, mday: number, month: number): string {
  return tr(lang, ('day' + wday) as StrKey) + ' ' + mday + ' ' + tr(lang, ('month' + month) as StrKey);
}
