#!/usr/bin/env python3
"""Index of firmware/deviations/ and emulator/deviations/ in each DEVIATIONS.md (issue #117).

One file per topic, NNN-slug.md (NNN = issue number, 000 = none), so two PRs never edit the same lines. Everything
below MARKER in DEVIATIONS.md is generated: one line per file, title from its first line. `make deviations` writes,
`--check` (make test) fails when the index is stale.
"""
import os
import re
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
DIRS = ('firmware', 'emulator')
MARKER = '<!-- generated by `make deviations` from deviations/*.md; do not edit below -->'
NAME = re.compile(r'^\d{3}-[a-z0-9-]+\.md$')


def title(path):
    with open(path, encoding='utf-8') as f:
        first = f.readline().strip()
    m = re.match(r'^(\d+)\. \*\*(.+?)\*\*', first)  # numbered emulator entries keep their number (cited elsewhere)
    t = f'{m.group(1)}. {m.group(2)}' if m else first.lstrip('#').strip()
    return t.rstrip('.:')


def render(top):
    index = os.path.join(ROOT, top, 'DEVIATIONS.md')
    with open(index, encoding='utf-8') as f:
        text = f.read()
    if MARKER not in text:
        raise SystemExit(f'{top}/DEVIATIONS.md: marker line missing')
    head = text.split(MARKER)[0]
    d = os.path.join(ROOT, top, 'deviations')
    names = sorted(os.listdir(d))
    bad = [n for n in names if not NAME.match(n)]
    if bad:
        raise SystemExit(f'{top}/deviations: not NNN-slug.md: {", ".join(bad)}')
    lines = [f'- [{title(os.path.join(d, n))}](deviations/{n})' for n in names]
    return index, text, head + MARKER + '\n\n' + '\n'.join(lines) + '\n'


def main(argv):
    check = '--check' in argv
    stale = []
    for top in DIRS:
        index, old, new = render(top)
        if old == new:
            continue
        if check:
            stale.append(f'{top}/DEVIATIONS.md')
        else:
            with open(index, 'w', encoding='utf-8') as f:
                f.write(new)
            print(f'wrote {top}/DEVIATIONS.md')
    if stale:
        print(f'stale index: {", ".join(stale)}; run `make deviations`', file=sys.stderr)
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
