// Persistent storage: NVS (Preferences) for credentials/tokens/flags; two LittleFS partitions (partitions.csv):
//  * `userdata` (128 KB, global LittleFS, readFile/writeFile): /screens.yaml, /settings.json, /diag.json. No flasher
//    writes it, so it survives a USB re-flash; formatted here on first mount.
//  * `www` (www.bin, rewritten by every flash and by net/www_ota.h): the web console under /www, served by net/web_server.cpp.
// Secrets go through SecretBox. Factory reset clears only HA Paper namespaces — the OEM `hw_calib`
// namespace (panel controller type, read by XteinkDetect) in the same NVS partition is preserved.
//
// What is persisted, and its schema version (issue eink-ha-os#12, core/migrate.h; migrate() runs once in begin()):
//   NVS x4wifi  ssid, pw (sealed)                          ┐
//   NVS x4ha    url, kind, cid, user, sec (sealed)         │ one number: x4dev/schema (I64, kDeviceSchema;
//   NVS x4tok   list (JSON array of API token hashes)      │ missing = 0). Older: device steps run, number
//   NVS x4dev   schema, iid, name, tz, entities (JSON)     │ written. Newer (OTA rollback): read, write nothing.
//   NVS x4ota   chan, ver, last                            ┘
//   /settings.json  `schema` key (kSettingsSchema; missing = 0), migrated at boot; saves keep unknown keys and a
//                   newer schema (core persistSettings).
//   /screens.yaml   `version: 1`, owned by core/config: any other version fails to parse → default config in RAM,
//                   the file is left as it is (nothing rewrites it at boot).
//   /diag.json      boot ring, not a setting: unversioned; an unreadable ring is dropped and rebuilt (core/diag).
//   /lang           HA's language as "en" | "nl" (eink-ha-os#98), rewritten only when it changes; empty = unlinked/unknown.
//   /numfmt         HA profile number_format as HA spells it (eink-ha-os#110), rewritten only when it changes; empty = unset.
//   NVS hw_calib    OEM, read-only, never touched.
#pragma once
#include <atomic>
#include <FS.h>

#include <mutex>
#include <string>

#include "app/app.h"

namespace x4::net {

struct WifiCreds { std::string ssid, password; };

struct HaLink {
  std::string kind;        // "oauth" | "llat" | "" (never linked)
  std::string url;         // http://homeassistant.local:8123
  std::string clientId;    // http://ha-paper-a1b2.local/ or http://<ip>/ (must stay identical for refresh)
  std::string secret;      // refresh_token (oauth) or long-lived token (llat) — plain in RAM only
  std::string user;        // display name from auth/current_user
  bool linked() const { return !kind.empty() && !secret.empty(); }
};

class Storage {
 public:
  bool begin();                          // mounts userdata (formats on first boot) and www (never formats)
  bool fsOk() const { return fsOk_; }
  bool wwwOk() const { return wwwOk_; }
  fs::FS& www();                         // web console files (/www/...); empty FS when wwwOk() is false
  void wwwUnmount();                     // before net/www_ota rewrites the partition (eink-ha-os#350)
  bool wwwRemount();                     // after it; false = not a LittleFS image (fallback page)

  bool loadWifi(WifiCreds& out);
  void saveWifi(const WifiCreds& c);
  void clearWifi();

  bool loadHa(HaLink& out);
  void saveHa(const HaLink& l);
  void clearHa();
  void saveHaUrl(const std::string& url);   // remembered even when unlinked (manual URL / discovery)
  std::string haUrl();

  std::string loadTokensJson();
  void saveTokensJson(const std::string& json);

  std::string getString(const char* ns, const char* key, const std::string& def = "");
  void putString(const char* ns, const char* key, const std::string& v);
  int64_t getI64(const char* ns, const char* key, int64_t def = 0);
  void putI64(const char* ns, const char* key, int64_t v);

  std::string installId();               // random per install; regenerated by factoryReset()

  bool readFile(const char* path, std::string& out);
  bool writeFile(const char* path, const std::string& data);   // atomic (tmp + rename)

  bool loadSettings(DisplaySettings& out);
  void saveSettings(const DisplaySettings& s);
  static std::string settingsToJson(const DisplaySettings& s);
  static bool settingsFromJson(const std::string& json, DisplaySettings& out, std::string* err = nullptr, bool strict = false);

  void factoryReset();                   // NVS namespaces above + formats userdata; keeps hw_calib and www

 private:
  void migrate();                        // schema check + upgrades, once per boot (end of begin())
  bool fsOk_ = false;
  std::atomic<bool> wwwOk_{false};
  std::recursive_mutex mu_;
};

Storage& storage();

}  // namespace x4::net
